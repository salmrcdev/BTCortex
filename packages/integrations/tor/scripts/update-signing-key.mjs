#!/usr/bin/env node
// Refreshes the pinned Tor Browser Developers signing key, which signs the
// Tor Expert Bundle and its checksum file.
//
//   node scripts/update-signing-key.mjs
//
// The key is fetched from the Tor Project's Web Key Directory (keys.openpgp.org
// as a fallback) and accepted only if its primary fingerprint equals the
// pinned one. Signing subkeys rotate, so run this when a new one appears,
// review the diff and commit it.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as openpgp from 'openpgp';

const PINNED_FINGERPRINT = 'EF6E286DDA85EA2A4BA7DE684E2C6E8793298290';
const SOURCES = [
  {
    url: 'https://openpgpkey.torproject.org/.well-known/openpgpkey/torproject.org/hu/kounek7zrdx745qydx6p59t9mqjpuhdf',
    binary: true,
  },
  { url: `https://keys.openpgp.org/vks/v1/by-fingerprint/${PINNED_FINGERPRINT}`, binary: false },
];

let key;
let source;
for (const candidate of SOURCES) {
  try {
    const response = await fetch(candidate.url);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const [read] = candidate.binary
      ? await openpgp.readKeys({ binaryKeys: new Uint8Array(await response.arrayBuffer()) })
      : await openpgp.readKeys({ armoredKeys: await response.text() });
    const fingerprint = read?.getFingerprint().toUpperCase();
    if (fingerprint !== PINNED_FINGERPRINT) {
      throw new Error(`fingerprint ${fingerprint ?? 'none'} is not the pinned ${PINNED_FINGERPRINT}`);
    }
    key = read;
    source = candidate.url;
    break;
  } catch (error) {
    console.error(`Skipping ${candidate.url}: ${error instanceof Error ? error.message : String(error)}`);
  }
}
if (!key) {
  console.error('No source returned the pinned key.');
  process.exit(1);
}

const day = (date) => (date instanceof Date ? date.toISOString().slice(0, 10) : null);
const subkeys = [];
for (const subkey of key.getSubkeys()) {
  subkeys.push({
    fingerprint: subkey.getFingerprint().toUpperCase(),
    created: day(subkey.getCreationTime()),
    expires: day(await subkey.getExpirationTime()),
  });
}
const expiry = await key.getExpirationTime();
const output = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src', 'signing-key.generated.ts');
writeFileSync(
  output,
  [
    `// Generated by scripts/update-signing-key.mjs from ${source}`,
    `// on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
    '',
    `export const TOR_SIGNING_KEY = ${JSON.stringify(
      {
        owner: key.getUserIDs()[0] ?? 'Tor Browser Developers (signing key) <torbrowser@torproject.org>',
        fingerprint: PINNED_FINGERPRINT,
        expires: day(expiry),
        subkeys,
        source,
        armored: key.armor(),
      },
      null,
      2,
    )} as const;`,
    '',
  ].join('\n'),
);
console.log(`Wrote ${output} (${PINNED_FINGERPRINT}, expires ${day(expiry) ?? 'never'})`);
console.log(JSON.stringify(subkeys, null, 2));
