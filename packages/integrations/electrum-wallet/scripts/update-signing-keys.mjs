#!/usr/bin/env node
// Refreshes the pinned Electrum release-signing keys: ThomasV's and
// SomberNight's release key, two of the five people who sign every Electrum
// release (docs/research/notes/wallets-hardware.md §4.1).
//
//   node scripts/update-signing-keys.mjs
//
// The keys are fetched from the pubkeys folder of Electrum's repository
// (keys.openpgp.org as a fallback) and accepted only if their primary
// fingerprints equal the pinned ones. Run this when a key changes, review the
// diff and commit it.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as openpgp from 'openpgp';

const PINNED = [
  {
    id: 'thomasv',
    owner: 'ThomasV',
    fingerprint: '6694D8DE7BE8EE5631BED9502BD5824B7F9470E6',
    sources: ['https://raw.githubusercontent.com/spesmilo/electrum/master/pubkeys/ThomasV.asc'],
  },
  {
    id: 'sombernight',
    owner: 'SomberNight (release key)',
    fingerprint: '0EEDCFD5CAFB459067349B23CA9EEEC43DF911DC',
    sources: ['https://raw.githubusercontent.com/spesmilo/electrum/master/pubkeys/sombernight_releasekey.asc'],
  },
];

const day = (date) => (date instanceof Date ? date.toISOString().slice(0, 10) : null);
const keys = [];
for (const pinned of PINNED) {
  const sources = [...pinned.sources, `https://keys.openpgp.org/vks/v1/by-fingerprint/${pinned.fingerprint}`];
  let found;
  for (const url of sources) {
    try {
      const response = await fetch(url);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const candidates = await openpgp.readKeys({ armoredKeys: await response.text() });
      const key = candidates.find((candidate) => candidate.getFingerprint().toUpperCase() === pinned.fingerprint);
      if (!key) throw new Error(`the pinned fingerprint ${pinned.fingerprint} is not among the keys`);
      found = { key, url };
      break;
    } catch (error) {
      console.error(`Skipping ${url}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  if (!found) {
    console.error(`No source returned ${pinned.owner}'s pinned key.`);
    process.exit(1);
  }
  keys.push({
    owner: pinned.owner,
    fingerprint: pinned.fingerprint,
    expires: day(await found.key.getExpirationTime()),
    source: found.url,
    armored: found.key.armor(),
  });
}

const output = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src', 'signing-keys.generated.ts');
writeFileSync(
  output,
  [
    `// Generated by scripts/update-signing-keys.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
    '',
    `export const ELECTRUM_SIGNING_KEYS = ${JSON.stringify(keys, null, 2)} as const;`,
    '',
  ].join('\n'),
);
for (const key of keys) console.log(`Wrote ${key.owner} (${key.fingerprint}, expires ${key.expires ?? 'never'})`);
