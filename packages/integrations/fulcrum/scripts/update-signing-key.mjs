#!/usr/bin/env node
// Refreshes the pinned Fulcrum release-signing key (Calin Culianu), which
// signs Fulcrum-<version>-shasums.txt. It is a DSA-2048 key, so BTCortex
// accepts DSA for this pinned key only.
//
//   node scripts/update-signing-key.mjs
//
// The key is fetched from the Electron Cash keys-n-hashes repository, where
// the author publishes it (the Ubuntu key server as a fallback), and accepted
// only if its primary fingerprint equals the pinned one. Run this when the
// key changes, review the diff and commit it.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as openpgp from 'openpgp';

const PINNED_FINGERPRINT = 'D465135F97D0047E18E99DC321810A542031C02C';
const SOURCES = [
  'https://raw.githubusercontent.com/Electron-Cash/keys-n-hashes/master/pubkeys/calinkey.txt',
  `https://keyserver.ubuntu.com/pks/lookup?op=get&options=mr&search=0x${PINNED_FINGERPRINT}`,
];

let key;
let source;
for (const url of SOURCES) {
  try {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const keys = await openpgp.readKeys({ armoredKeys: await response.text() });
    const found = keys.find((candidate) => candidate.getFingerprint().toUpperCase() === PINNED_FINGERPRINT);
    if (!found) throw new Error(`the pinned fingerprint ${PINNED_FINGERPRINT} is not among the keys`);
    key = found;
    source = url;
    break;
  } catch (error) {
    console.error(`Skipping ${url}: ${error instanceof Error ? error.message : String(error)}`);
  }
}
if (!key) {
  console.error('No source returned the pinned key.');
  process.exit(1);
}

const day = (date) => (date instanceof Date ? date.toISOString().slice(0, 10) : null);
const expiry = await key.getExpirationTime();
const output = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src', 'signing-key.generated.ts');
writeFileSync(
  output,
  [
    `// Generated by scripts/update-signing-key.mjs from ${source}`,
    `// on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
    '',
    `export const FULCRUM_SIGNING_KEY = ${JSON.stringify(
      {
        owner: key.getUserIDs()[0] ?? 'Calin Culianu',
        fingerprint: PINNED_FINGERPRINT,
        expires: day(expiry),
        source,
        armored: key.armor(),
      },
      null,
      2,
    )} as const;`,
    '',
  ].join('\n'),
);
console.log(`Wrote ${output} (${PINNED_FINGERPRINT}, expires ${day(expiry) ?? 'never'})`);
