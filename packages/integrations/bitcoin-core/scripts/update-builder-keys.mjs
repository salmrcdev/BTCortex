#!/usr/bin/env node
// Refreshes the pinned Bitcoin Core builder keys from bitcoin-core/guix.sigs.
//
//   node scripts/update-builder-keys.mjs <commit-sha>
//
// Writes src/release/builder-keys.generated.ts (the keys BTCortex trusts,
// bundled into the application) and keys/bitcoin-core/manifest.json (the same
// fingerprints and user ids, for review). Trust anchors change only through a
// reviewed BTCortex release: run this, inspect the manifest diff, commit it.
// The application never adds keys at run time.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as openpgp from 'openpgp';

const commit = process.argv[2];
if (!commit || !/^[0-9a-f]{40}$/.test(commit)) {
  console.error('Usage: node scripts/update-builder-keys.mjs <40-character commit sha of bitcoin-core/guix.sigs>');
  process.exit(1);
}

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifestDir = join(packageDir, 'keys', 'bitcoin-core');
const generatedFile = join(packageDir, 'src', 'release', 'builder-keys.generated.ts');
const headers = { 'User-Agent': 'btcortex-builder-key-update', Accept: 'application/vnd.github+json' };
const retrievedOn = new Date().toISOString().slice(0, 10);

const listing = await (
  await fetch(`https://api.github.com/repos/bitcoin-core/guix.sigs/contents/builder-keys?ref=${commit}`, { headers })
).json();
if (!Array.isArray(listing)) throw new Error(`Unexpected GitHub response: ${JSON.stringify(listing).slice(0, 200)}`);

const manifest = {
  source: `https://github.com/bitcoin-core/guix.sigs/tree/${commit}/builder-keys`,
  commit,
  retrievedOn,
  keys: [],
};
const bundled = [];

for (const entry of listing.filter((item) => item.name.endsWith('.gpg')).sort((a, b) => a.name.localeCompare(b.name))) {
  const url = `https://raw.githubusercontent.com/bitcoin-core/guix.sigs/${commit}/builder-keys/${entry.name}`;
  const armored = await (await fetch(url)).text();
  const builder = entry.name.replace(/\.gpg$/, '');
  const record = { builder, primaries: [], note: null };
  try {
    const keys = await openpgp.readKeys({ armoredKeys: armored });
    record.primaries = keys.map((key) => ({
      fingerprint: key.getFingerprint().toUpperCase(),
      algorithm: key.getAlgorithmInfo().algorithm,
      userIds: key.getUserIDs(),
    }));
    bundled.push({ builder, fingerprints: record.primaries.map((primary) => primary.fingerprint), armored });
  } catch (error) {
    record.note = `Not bundled: OpenPGP.js cannot load this key (${error instanceof Error ? error.message : String(error)}).`;
  }
  manifest.keys.push(record);
  console.log(
    `${record.note ? 'SKIP' : 'ok  '} ${builder} ${record.primaries.map((primary) => primary.fingerprint).join(', ')}`,
  );
}

mkdirSync(manifestDir, { recursive: true });
writeFileSync(join(manifestDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(
  generatedFile,
  [
    `// Generated by scripts/update-builder-keys.mjs from bitcoin-core/guix.sigs@${commit}`,
    `// on ${retrievedOn}. Do not edit by hand; review keys/bitcoin-core/manifest.json instead.`,
    '',
    'export interface BuilderKey {',
    '  readonly builder: string;',
    '  /** Primary key fingerprints, upper-case hex. */',
    '  readonly fingerprints: readonly string[];',
    '  readonly armored: string;',
    '}',
    '',
    `export const BUILDER_KEYS_SOURCE = ${JSON.stringify({ repository: 'https://github.com/bitcoin-core/guix.sigs', commit, retrievedOn })} as const;`,
    '',
    `export const BUILDER_KEYS: readonly BuilderKey[] = ${JSON.stringify(bundled, null, 2)};`,
    '',
  ].join('\n'),
);
console.log(`Bundled ${bundled.length} of ${manifest.keys.length} keys into ${generatedFile}`);
