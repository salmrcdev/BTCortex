#!/usr/bin/env node
// Refreshes the pinned Sparrow release-signing key (Craig Raw).
//
//   node scripts/update-signing-key.mjs
//
// The key is fetched from keybase.io and accepted only if its primary
// fingerprint equals the pinned one; run this when the key's expiry is
// extended, review the diff and commit it.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as openpgp from 'openpgp';

const PINNED_FINGERPRINT = 'D4D0D3202FC06849A257B38DE94618334C674B40';
const SOURCE = 'https://keybase.io/craigraw/pgp_keys.asc';

const armored = await (await fetch(SOURCE)).text();
const [key] = await openpgp.readKeys({ armoredKeys: armored });
const fingerprint = key?.getFingerprint().toUpperCase();
if (fingerprint !== PINNED_FINGERPRINT) {
  console.error(
    `Refusing the key from ${SOURCE}: fingerprint ${fingerprint ?? 'none'} is not the pinned ${PINNED_FINGERPRINT}.`,
  );
  process.exit(1);
}
const expiry = await key.getExpirationTime();
const output = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src', 'signing-key.generated.ts');
writeFileSync(
  output,
  [
    `// Generated by scripts/update-signing-key.mjs from ${SOURCE}`,
    `// on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
    '',
    `export const SPARROW_SIGNING_KEY = ${JSON.stringify(
      {
        owner: key.getUserIDs()[0] ?? 'Craig Raw',
        fingerprint,
        expires: expiry instanceof Date ? expiry.toISOString().slice(0, 10) : null,
        source: SOURCE,
        armored,
      },
      null,
      2,
    )} as const;`,
    '',
  ].join('\n'),
);
console.log(
  `Wrote ${output} (${fingerprint}, expires ${expiry instanceof Date ? expiry.toISOString().slice(0, 10) : 'never'})`,
);
