#!/usr/bin/env node
// Refreshes the pinned SatoshiLabs 2021 Signing Key, which signs the
// Trezor Suite installers.
//
//   node scripts/update-signing-key.mjs
//
// The key is fetched from trezor.io
// (keys.openpgp.org as a fallback) and accepted only if its primary
// fingerprint equals the pinned one. Run this when the key's expiry is
// extended, review the diff and commit it.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as openpgp from 'openpgp';

const PINNED_FINGERPRINT = 'EB483B26B078A4AA1B6F425EE21B6950A2ECB65C';
const SOURCES = [
  'https://trezor.io/security/satoshilabs-2021-signing-key.asc',
  `https://keys.openpgp.org/vks/v1/by-fingerprint/${PINNED_FINGERPRINT}`,
];

let key;
let source;
for (const url of SOURCES) {
  try {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const keys = await openpgp.readKeys({ armoredKeys: await response.text() });
    const found = keys.find((candidate) => candidate.getFingerprint().toUpperCase() === PINNED_FINGERPRINT);
    if (!found) throw new Error(`the pinned fingerprint ${PINNED_FINGERPRINT} is not among the keys`);
    key = found;
    source = url;
    break;
  } catch (error) {
    console.error(`Skipping ${url}: ${error instanceof Error ? error.message : String(error)}`);
  }
}
if (!key) {
  console.error('No source returned the pinned key.');
  process.exit(1);
}

const day = (date) => (date instanceof Date ? date.toISOString().slice(0, 10) : null);
const expiry = await key.getExpirationTime();
const output = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src', 'signing-key.generated.ts');
writeFileSync(
  output,
  [
    `// Generated by scripts/update-signing-key.mjs from ${source}`,
    `// on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
    '',
    `export const SATOSHILABS_SIGNING_KEY = ${JSON.stringify(
      {
        owner: key.getUserIDs()[0] ?? 'SatoshiLabs 2021 Signing Key',
        fingerprint: PINNED_FINGERPRINT,
        expires: day(expiry),
        source,
        armored: key.armor(),
      },
      null,
      2,
    )} as const;`,
    '',
  ].join('\n'),
);
console.log(`Wrote ${output} (${PINNED_FINGERPRINT}, expires ${day(expiry) ?? 'never'})`);
