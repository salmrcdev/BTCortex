#!/usr/bin/env node
// Refreshes the pinned LND release-signing keys: every key LND's own
// scripts/verify-install.sh accepts, and the number of signatures it requires
// (docs/research/notes/lightning.md, section 2.1).
//
//   node scripts/update-signing-keys.mjs [tag]
//
// The fingerprints and the threshold come from verify-install.sh at the tag
// (the latest final release by default), each key from scripts/keys/<user>.asc
// at the same tag; a key is accepted only if its primary fingerprint is the
// listed one. Run this when LND's signers change, review the diff and commit it.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as openpgp from 'openpgp';

const REPOSITORY = 'lightningnetwork/lnd';
const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'BTCortex' };

async function text(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${url} answered HTTP ${response.status}`);
  return response.text();
}

let tag = process.argv[2];
if (!tag) {
  const latest = JSON.parse(await text(`https://api.github.com/repos/${REPOSITORY}/releases/latest`));
  tag = latest.tag_name;
}
const script = await text(`https://raw.githubusercontent.com/${REPOSITORY}/${tag}/scripts/verify-install.sh`);
const required = Number(/^MIN_REQUIRED_SIGNATURES=(\d+)$/m.exec(script)?.[1]);
const listed = [...script.matchAll(/^KEYS\+=\("([0-9A-F]{40}) ([A-Za-z0-9_-]+)"\)$/gm)].map((match) => ({
  fingerprint: match[1],
  owner: match[2],
}));
if (!Number.isInteger(required) || required < 1 || listed.length < required) {
  console.error(`verify-install.sh at ${tag} lists ${listed.length} keys and requires ${required}; refusing.`);
  process.exit(1);
}

const day = (date) => (date instanceof Date ? date.toISOString().slice(0, 10) : null);
const keys = [];
for (const { fingerprint, owner } of listed) {
  const source = `https://raw.githubusercontent.com/${REPOSITORY}/${tag}/scripts/keys/${owner}.asc`;
  const candidates = await openpgp.readKeys({ armoredKeys: await text(source) });
  const key = candidates.find((candidate) => candidate.getFingerprint().toUpperCase() === fingerprint);
  if (!key) {
    console.error(`${source} does not hold the listed key ${fingerprint}; refusing.`);
    process.exit(1);
  }
  keys.push({ owner, fingerprint, expires: day(await key.getExpirationTime()), source, armored: key.armor() });
}

const output = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src', 'signing-keys.generated.ts');
writeFileSync(
  output,
  [
    `// Generated by scripts/update-signing-keys.mjs from LND ${tag} on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
    '',
    `export const LND_SIGNING_KEYS_TAG = ${JSON.stringify(tag)};`,
    '',
    '/** As in scripts/verify-install.sh: signatures from this many distinct listed keys. */',
    `export const LND_REQUIRED_SIGNATURES = ${required};`,
    '',
    `export const LND_SIGNING_KEYS = ${JSON.stringify(keys, null, 2)} as const;`,
    '',
  ].join('\n'),
);
console.log(`LND ${tag}: ${keys.length} keys, ${required} signatures required.`);
for (const key of keys) console.log(`  ${key.owner} ${key.fingerprint} expires ${key.expires ?? 'never'}`);
