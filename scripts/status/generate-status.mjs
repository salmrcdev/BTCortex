#!/usr/bin/env node
// Generates docs/IMPLEMENTATION_STATUS.md from docs/implementation/features.json,
// the machine-readable feature manifest (specification section 36).
//
//   node scripts/status/generate-status.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { IMPLEMENTATION_STATUSES } from '../research/schema.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const features = JSON.parse(readFileSync(join(root, 'docs', 'implementation', 'features.json'), 'utf8'));

const LABELS = {
  researched: 'Researched',
  designed: 'Designed',
  implemented: 'Implemented',
  'unit-tested': 'Unit tested',
  'integration-tested': 'Integration tested',
  'verified-on-windows': 'Verified on Windows',
  'production-ready': 'Production ready',
  experimental: 'Experimental',
  blocked: 'Blocked',
  unsupported: 'Unsupported',
};

const ids = new Set();
for (const feature of features) {
  if (!IMPLEMENTATION_STATUSES.includes(feature.state))
    throw new Error(`${feature.id}: unknown state "${feature.state}"`);
  if (ids.has(feature.id)) throw new Error(`Duplicate feature id ${feature.id}`);
  ids.add(feature.id);
}

const cell = (value) => (value ? String(value).replace(/\|/g, '\\|') : '—');
const lines = [
  '# BTCortex implementation status',
  '',
  '> Generated by `scripts/status/generate-status.mjs` from [`implementation/features.json`](implementation/features.json). Do not edit by hand.',
  '',
  'Each feature shows the highest state it has actually reached. A rendered interface is not an implemented feature, and code that compiles is not a tested integration (specification section 36).',
  '',
  '| State | Features |',
  '|---|---|',
  ...IMPLEMENTATION_STATUSES.map((state) => [state, features.filter((feature) => feature.state === state).length])
    .filter(([, count]) => count > 0)
    .map(([state, count]) => `| ${LABELS[state]} | ${count} |`),
  '',
];

for (const area of [...new Set(features.map((feature) => feature.area))]) {
  lines.push(`## ${area}`, '', '| Feature | State | Specification | Evidence | Notes |', '|---|---|---|---|---|');
  for (const feature of features.filter((candidate) => candidate.area === area)) {
    lines.push(
      `| ${cell(feature.title)} | ${LABELS[feature.state]} | ${feature.specSections.map((section) => `§${section}`).join(', ')} | ${cell(feature.evidence.join('<br>'))} | ${cell(feature.notes)} |`,
    );
  }
  lines.push('');
}

writeFileSync(join(root, 'docs', 'IMPLEMENTATION_STATUS.md'), `${lines.join('\n').trimEnd()}\n`);
console.log(`wrote docs/IMPLEMENTATION_STATUS.md (${features.length} features)`);
