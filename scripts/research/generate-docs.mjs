function renderIntegrationMatrix() {
  const catalogue = entries.filter((entry) => entry.catalogueEligible);
  const lines = [];
  lines.push('# BTCortex integration matrix');
  lines.push('');
  lines.push(GENERATED_NOTICE);
  lines.push('');
  lines.push(
    `Records verified up to **${verifiedUpTo}**. ${catalogue.length} catalogue-eligible entries out of ${entries.length}.`,
  );
  lines.push('');
  lines.push(
    'Every entry declares the support level BTCortex intends to offer. A level describes the *target* integration; the implementation status column shows how far that integration has actually progressed. Only entries at *Implemented* or later may be presented in the application as working.',
  );
  lines.push('');
  lines.push('## Support levels');
  lines.push('');
  lines.push('| Level | Meaning | Recommended for |');
  lines.push('|---|---|---|');
  for (const level of SUPPORT_LEVELS) {
    const count = catalogue.filter((entry) => entry.recommendedSupportLevel === level).length;
    lines.push(`| ${SUPPORT_LEVEL_LABELS[level]} | ${SUPPORT_LEVEL_DESCRIPTIONS[level]} | ${count} |`);
  }
  lines.push('');
  lines.push('## Windows execution summary');
  lines.push('');
  lines.push('| Native Windows | Entries |');
  lines.push('|---|---|');
  for (const value of ['yes', 'partial', 'no', 'unknown', 'not-applicable']) {
    const matching = catalogue.filter((entry) => entry.platforms.windowsNative === value);
    if (matching.length > 0) lines.push(`| ${value} | ${matching.map(link).join(', ')} |`);
  }
  lines.push('');

  for (const priority of ['P0', 'P1', 'P2', 'P3']) {
    const items = catalogue.filter((entry) => entry.priority === priority);
    if (items.length === 0) continue;
    const titles = {
      P0: 'P0 — Bitcoin Core vertical slice',
      P1: 'P1 — Essential ecosystem integrations',
      P2: 'P2 — Lightning, payments and advanced features',
      P3: 'P3 — Optional and later integrations',
    };
    lines.push(`## ${titles[priority]}`);
    lines.push('');
    lines.push(
      '| Entry | Category | Maintenance | Latest release | Windows native | Arch | WSL2 | Docker | Recommended level | Other feasible levels | Feasibility | Status |',
    );
    lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|');
    for (const entry of items) {
      const others = entry.supportLevels
        .filter((level) => level !== entry.recommendedSupportLevel)
        .map((level) => SUPPORT_LEVEL_LABELS[level]);
      lines.push(
        `| ${link(entry)} | ${cell(CATEGORY_LABELS[entry.category])} | ${cell(entry.maintenance.status)} | ${cell(release(entry))} | ${cell(entry.platforms.windowsNative)} | ${cell(architectures(entry))} | ${cell(entry.platforms.wsl2)} | ${cell(entry.platforms.docker)} | ${cell(SUPPORT_LEVEL_LABELS[entry.recommendedSupportLevel])} | ${cell(others.join(', '))} | ${cell(entry.feasibility.rating)} | ${cell(entry.implementationStatus)} |`,
      );
    }
    lines.push('');
  }

  const excluded = entries.filter((entry) => !entry.catalogueEligible);
  if (excluded.length > 0) {
    lines.push('## Researched but not offered in the catalogue');
    lines.push('');
    lines.push(
      'Libraries, hosted services and discontinued or unsuitable projects are recorded so that their exclusion is explicit.',
    );
    lines.push('');
    lines.push('| Entry | Category | Maintenance | Reason (feasibility notes) |');
    lines.push('|---|---|---|---|');
    for (const entry of excluded) {
      lines.push(
        `| ${link(entry)} | ${cell(CATEGORY_LABELS[entry.category])} | ${cell(entry.maintenance.status)} | ${cell(entry.feasibility.notes)} |`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}

