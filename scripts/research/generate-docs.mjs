#!/usr/bin/env node
// Generates docs/ECOSYSTEM_RESEARCH.md, docs/INTEGRATION_MATRIX.md and
// docs/DEPENDENCY_MATRIX.md from the research records in docs/research/.
//
//   node scripts/research/generate-docs.mjs
//
// The output is deterministic: it depends only on the records, never on the
// current date, so regenerating unchanged data produces identical files.

