function renderInterfaces(entry) {
  if (entry.interfaces.length === 0) return '—';
  return entry.interfaces
    .map((iface) => {
      const auth = iface.authentication ? ` — authentication: ${iface.authentication}` : '';
      const docs = iface.documentation ? ` ([documentation](${iface.documentation}))` : '';
      return `\`${iface.type}\`: ${iface.description}${auth}${docs}`;
    })
    .join('<br>');
}

function renderDependencies(entry) {
  if (entry.dependencies.length === 0) return 'None recorded';
  return entry.dependencies
    .map((dependency) => {
      const targets = dependency.ids
        .map((id) => (entryById.has(id) ? `[${entryById.get(id).name}](#${anchor(id)})` : `\`${id}\``))
        .join(' or ');
      const notes = dependency.notes ? ` — ${dependency.notes}` : '';
      return `${dependency.relationship}: ${targets}${notes}`;
    })
    .join('<br>');
}

function renderEntry(entry) {
  const p = entry.platforms;
  const rows = [
    ['Category', CATEGORY_LABELS[entry.category]],
    ['Purpose', entry.purpose],
    ['Official website', entry.website ? `<${entry.website}>` : null],
    ['Official repository', entry.repository ? `<${entry.repository}>` : null],
    ['Maintenance status', `${entry.maintenance.status} — ${entry.maintenance.evidence}`],
    ['Superseded by', entry.maintenance.supersededBy],
    [
      'Latest verified stable release',
      entry.latestStableRelease ? `${release(entry)} — <${entry.latestStableRelease.source}>` : null,
    ],
    ['Verification date', entry.verifiedOn],
    ['Native Windows', p.windowsNative],
    ['Windows versions', p.windowsVersions],
    ['Windows architectures', architectures(entry)],
    ['Windows distribution', p.windowsDistribution],
    ['WSL2', p.wsl2],
    ['Docker', p.docker],
    ['Other platforms', p.other],
    ['APIs and interfaces', renderInterfaces(entry)],
    ['Command-line interface', entry.cli],
    ['Remote management', entry.remoteManagement],
    ['Node compatibility', entry.nodeCompatibility],
    ['Dependencies', renderDependencies(entry)],
    ['Networking', entry.networking],
    ['Storage', entry.storage],
    ['Resources', entry.resources],
    ['Security implications', entry.security],
    ['Licence', entry.licence],
    ['Licence notes', entry.licenceNotes],
    [
      'Integration mechanisms',
      entry.integrationMechanisms.length > 0 ? entry.integrationMechanisms.join('<br>') : null,
    ],
    ['Feasible support levels', entry.supportLevels.map((level) => SUPPORT_LEVEL_LABELS[level]).join(', ')],
    ['Recommended support level', SUPPORT_LEVEL_LABELS[entry.recommendedSupportLevel]],
    ['Implementation feasibility', `${entry.feasibility.rating} — ${entry.feasibility.notes}`],
    ['Priority', entry.priority],
    ['Implementation status', entry.implementationStatus],
    ['In-app catalogue', entry.catalogueEligible ? 'Yes' : 'No'],
    ['Notes', entry.notes],
  ];

  const lines = [];
  lines.push(`<a id="${anchor(entry.id)}"></a>`);
  lines.push('');
  lines.push(`### ${entry.name}`);
  lines.push('');
  lines.push('| Field | Value |');
  lines.push('|---|---|');
  for (const [label, value] of rows) {
    // Interfaces and dependencies are pre-rendered Markdown; escape only plain values.
    const rendered = label === 'APIs and interfaces' || label === 'Dependencies' ? value : cell(value);
    lines.push(`| ${label} | ${rendered} |`);
  }
  lines.push('');
  lines.push('**Evidence and sources**');
  lines.push('');
  for (const source of entry.sources) lines.push(`- [${source.title}](${source.url}) (accessed ${source.accessed})`);
  if (entry.unverifiedClaims.length > 0) {
    lines.push('');
    lines.push('**Requires verification**');
    lines.push('');
    for (const claim of entry.unverifiedClaims) lines.push(`- ${claim}`);
  }
  lines.push('');
  return lines.join('\n');
}

function renderResearchDocument() {
  const groups = entriesByCategory();
  const statusCounts = new Map();
  for (const entry of entries)
    statusCounts.set(entry.maintenance.status, (statusCounts.get(entry.maintenance.status) ?? 0) + 1);
  const unverifiedTotal = entries.reduce((sum, entry) => sum + entry.unverifiedClaims.length, 0);

  const lines = [];
  lines.push('# BTCortex ecosystem research');
  lines.push('');
  lines.push(GENERATED_NOTICE);
  lines.push('');
  lines.push(
    `Records verified up to **${verifiedUpTo}**. ${entries.length} ecosystem entries, ${standards.length} standards and ${packages.length} technology-stack packages.`,
  );
  lines.push('');
  lines.push('## Method');
  lines.push('');
  lines.push(
    'Each record was researched live from primary sources (official websites, repositories, release pages, documentation and security advisories) on its verification date. Claims that could not be verified live are listed under *Requires verification* and must not be presented as current. The data contract, research rules and scope ownership are defined in [`research/README.md`](research/README.md).',
  );
  lines.push('');
  lines.push(
    `Maintenance status across all entries: ${[...statusCounts.entries()]
      .sort()
      .map(([status, count]) => `${status} ${count}`)
      .join(', ')}. Open verification items: ${unverifiedTotal}.`,
  );
  lines.push('');
  if (noteFiles.length > 0) {
    lines.push('## Research notes by scope');
    lines.push('');
    lines.push(
      'The notes contain the integration detail behind the records: interfaces, configuration formats, Windows pitfalls and open questions.',
    );
    lines.push('');
    for (const name of noteFiles) lines.push(`- [${name.replace(/\.md$/, '')}](research/notes/${name})`);
    lines.push('');
  }
  lines.push('## Contents');
  lines.push('');
  for (const group of groups) {
    lines.push(
      `- **${CATEGORY_LABELS[group.category]}**: ${group.items.map((entry) => `[${entry.name}](#${anchor(entry.id)})`).join(', ')}`,
    );
  }
  if (standards.length > 0) lines.push('- [Standards and specifications](#standards-and-specifications)');
  if (packages.length > 0) lines.push('- [Application technology stack](#application-technology-stack)');
  lines.push('');

  for (const group of groups) {
    lines.push(`## ${CATEGORY_LABELS[group.category]}`);
    lines.push('');
    for (const entry of group.items) lines.push(renderEntry(entry));
  }

  if (standards.length > 0) {
    lines.push('## Standards and specifications');
    lines.push('');
    lines.push('| Standard | Title | Status | Relevance to BTCortex | Implemented in | Sources |');
    lines.push('|---|---|---|---|---|---|');
    for (const standard of standards) {
      const name = standard.number ? `${standard.kind} ${standard.number}` : standard.kind;
      const sources = standard.sources.map((source) => `[${cell(source.title)}](${source.url})`).join('<br>');
      lines.push(
        `| ${cell(name)} | ${cell(standard.title)} | ${cell(standard.status)} | ${cell(`${standard.summary} ${standard.relevance}`)} | ${cell(standard.implementedIn.join('; '))} | ${sources} |`,
      );
    }
    lines.push('');
  }

  if (packages.length > 0) {
    lines.push('## Application technology stack');
    lines.push('');
    lines.push('| Package | Ecosystem | Latest version | Licence | Decision | Purpose and rationale | Windows notes |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const pkg of packages) {
      const version = pkg.latestVersion
        ? `${pkg.latestVersion}${pkg.releaseDate ? ` (${pkg.releaseDate})` : ''}`
        : null;
      lines.push(
        `| ${cell(pkg.name)} | ${cell(pkg.ecosystem)} | ${cell(version)} | ${cell(pkg.licence)} | ${cell(pkg.decision)} | ${cell(`${pkg.purpose} ${pkg.rationale}`)} | ${cell(pkg.windowsNotes)} |`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}

