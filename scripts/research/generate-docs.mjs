const GENERATED_NOTICE =
  '> Generated by `scripts/research/generate-docs.mjs` from the records in [`docs/research/`](research/README.md). Do not edit by hand: change the records and regenerate.';

function listJson(dir, predicate = () => true) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith('.json') && predicate(name))
    .sort()
    .map((name) => join(dir, name));
}

function readRecords(file) {
  const records = JSON.parse(readFileSync(file, 'utf8'));
  return records.map((record) => ({ ...record, sourceFile: basename(file) }));
}

function cell(value) {
  if (value === null || value === undefined || value === '') return '—';
  return String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
}

function anchor(id) {
  return `entry-${id}`;
}

function link(entry) {
  return `[${cell(entry.name)}](ECOSYSTEM_RESEARCH.md#${anchor(entry.id)})`;
}

function release(entry) {
  const r = entry.latestStableRelease;
  if (!r) return '—';
  return r.date ? `${r.version} (${r.date})` : r.version;
}

function architectures(entry) {
  const archs = entry.platforms.windowsArchitectures;
  return archs.length > 0 ? archs.join(', ') : '—';
}

function byName(a, b) {
  return a.name.localeCompare(b.name, 'en-GB', { sensitivity: 'base' });
}

function latestVerification(records) {
  return (
    records
      .map((r) => r.verifiedOn)
      .filter(Boolean)
      .sort()
      .at(-1) ?? 'unknown'
  );
}

const entryFiles = listJson(dataDir, (name) => !name.startsWith('standards-'));
const standardFiles = listJson(dataDir, (name) => name.startsWith('standards-'));
const packageFiles = listJson(techStackDir);

const entries = entryFiles.flatMap(readRecords).sort(byName);
const standards = standardFiles
  .flatMap(readRecords)
  .sort((a, b) => a.id.localeCompare(b.id, 'en-GB', { numeric: true }));
const packages = packageFiles.flatMap(readRecords).sort((a, b) => a.name.localeCompare(b.name, 'en-GB'));
const entryById = new Map(entries.map((entry) => [entry.id, entry]));
const noteFiles = existsSync(notesDir)
  ? readdirSync(notesDir)
      .filter((name) => name.endsWith('.md'))
      .sort()
  : [];
const verifiedUpTo = latestVerification(entries);

function entriesByCategory() {
  return CATEGORIES.map((category) => ({
    category,
    items: entries.filter((entry) => entry.category === category),
  })).filter((group) => group.items.length > 0);
}

