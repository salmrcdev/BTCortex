// DEPENDENCY_MATRIX.md
// ---------------------------------------------------------------------------

function findRequiresCycles() {
  // A dependency with several ids is satisfied by any one of them, so only
  // single-id "requires" edges can form an unavoidable cycle.
  const edges = new Map();
  for (const entry of entries) {
    edges.set(
      entry.id,
      entry.dependencies.filter((d) => d.relationship === 'requires' && d.ids.length === 1).map((d) => d.ids[0]),
    );
  }
  const cycles = [];
  const state = new Map();
  const stack = [];
  const visit = (id) => {
    state.set(id, 'active');
    stack.push(id);
    for (const next of edges.get(id) ?? []) {
      if (state.get(next) === 'active') cycles.push([...stack.slice(stack.indexOf(next)), next]);
      else if (!state.has(next) && edges.has(next)) visit(next);
    }
    stack.pop();
    state.set(id, 'done');
  };
  for (const id of edges.keys()) if (!state.has(id)) visit(id);
  return cycles;
}

function renderDependencyMatrix() {
  const withDependencies = entries.filter((entry) => entry.dependencies.length > 0);
  const reverse = new Map();
  const unknown = [];
  for (const entry of entries) {
    for (const dependency of entry.dependencies) {
      for (const id of dependency.ids) {
        if (!entryById.has(id)) unknown.push(`\`${id}\` (from ${entry.name})`);
        if (!reverse.has(id)) reverse.set(id, []);
        reverse.get(id).push({ entry, relationship: dependency.relationship });
      }
    }
  }

  const target = (id) => (entryById.has(id) ? link(entryById.get(id)) : `\`${id}\``);
  const column = (entry, relationship) =>
    entry.dependencies
      .filter((d) => d.relationship === relationship)
      .map((d) => d.ids.map(target).join(' or ') + (d.notes ? ` — ${cell(d.notes)}` : ''))
      .join('<br>') || '—';

  const lines = [];
  lines.push('# BTCortex dependency matrix');
  lines.push('');
  lines.push(GENERATED_NOTICE);
  lines.push('');
  lines.push(
    'Dependencies between researched components. Several targets joined by *or* mean that any one of them satisfies the dependency. The orchestration engine uses the same relationships to plan installation order, detect missing prerequisites and explain blocked operations.',
  );
  lines.push('');
  lines.push('## Forward dependencies');
  lines.push('');
  lines.push('| Entry | Requires | Optional | Enhances | Conflicts |');
  lines.push('|---|---|---|---|---|');
  for (const entry of withDependencies) {
    lines.push(
      `| ${link(entry)} | ${column(entry, 'requires')} | ${column(entry, 'optional')} | ${column(entry, 'enhances')} | ${column(entry, 'conflicts')} |`,
    );
  }
  lines.push('');
  lines.push('## Reverse dependencies');
  lines.push('');
  lines.push('| Component | Required by | Used optionally or enhanced by | Conflicts with |');
  lines.push('|---|---|---|---|');
  const reverseIds = [...reverse.keys()].sort((a, b) =>
    (entryById.get(a)?.name ?? a).localeCompare(entryById.get(b)?.name ?? b, 'en-GB'),
  );
  for (const id of reverseIds) {
    const refs = reverse.get(id);
    const pick = (relationships) =>
      [...new Set(refs.filter((ref) => relationships.includes(ref.relationship)).map((ref) => link(ref.entry)))].join(
        ', ',
      ) || '—';
    lines.push(
      `| ${target(id)} | ${pick(['requires'])} | ${pick(['optional', 'enhances'])} | ${pick(['conflicts'])} |`,
    );
  }
  lines.push('');
  lines.push('## Consistency checks');
  lines.push('');
  const cycles = findRequiresCycles();
  lines.push(
    cycles.length === 0
      ? '- No unavoidable *requires* cycles.'
      : cycles.map((cycle) => `- Cycle: ${cycle.join(' → ')}`).join('\n'),
  );
  lines.push(
    unknown.length === 0
      ? '- Every dependency refers to a researched entry.'
      : `- Dependencies on ids without a research record: ${[...new Set(unknown)].join(', ')}.`,
  );
  lines.push('');
  return lines.join('\n');
}

const outputs = [
  ['ECOSYSTEM_RESEARCH.md', renderResearchDocument()],
  ['INTEGRATION_MATRIX.md', renderIntegrationMatrix()],
  ['DEPENDENCY_MATRIX.md', renderDependencyMatrix()],
];
for (const [name, content] of outputs) {
  writeFileSync(join(root, 'docs', name), `${content.trimEnd()}\n`, 'utf8');
  console.log(`wrote docs/${name}`);
}
